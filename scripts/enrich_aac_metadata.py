def infer_assembly_objects(label: str) -> list[str]:
    text = normalize(label)
    found: list[str] = []

    # 긴 표현을 먼저 검사해서 '큰 부품'과 '부품'처럼 겹치는 표현에서
    # 더 구체적인 객체가 먼저 들어가게 한다.
    rules = sorted(
        ASSEMBLY_OBJECT_RULES.items(),
        key=lambda item: max(len(x) for x in item[1]),
        reverse=True,
    )
    for canonical, patterns in rules:
        if any(pattern in text for pattern in patterns):
            found.append(canonical)

    # 구체 객체가 있으면 지나치게 일반적인 객체를 일부 제거한다.
    if any(x in found for x in ("큰 부품", "작은 부품", "왼쪽 부품", "오른쪽 부품")):
        found = [x for x in found if x != "부품"]
    if "완성품" in found:
        found = [x for x in found if x != "제품"]
    if "불량 제품" in found:
        found = [x for x in found if x not in {"제품", "완성품"}]
    if "불량품 통" in found:
        # 통 자체와 불량 제품이 동시에 문장에 있으면 둘 다 유지한다.
        pass

    return unique(found)


