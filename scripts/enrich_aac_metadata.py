def load_json(path: Path) -> Any:
    with path.open(
        "r",
        encoding="utf-8",
    ) as f:
        return json.load(f)


def save_json(path: Path, data: Any) -> None:
    with path.open(
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            data,
            f,
            ensure_ascii=False,
            indent=2,
        )
        f.write("\n")


def get_assets(data: Any) -> list[dict]:
    """
    aac_assets.json이 아래 두 형태여도 처리한다.

    1)
    [
        {...},
        {...}
    ]

    2)
    {
        "assets": [
            {...},
            {...}
        ]
    }
    """

    if isinstance(data, list):
        return data

    if (
        isinstance(data, dict)
        and isinstance(data.get("assets"), list)
    ):
        return data["assets"]

    raise ValueError(
        "aac_assets.json 형식을 확인할 수 없습니다. "
        "list 또는 {'assets': [...]} 형태여야 합니다."
    )


def normalize(text: str) -> str:
    return re.sub(
        r"\s+",
        " ",
        str(text or "").strip(),
    )


def unique(items: list[str]) -> list[str]:
    seen = set()
    result = []

    for item in items:
        item = normalize(item)

        if not item:
            continue

        if item in seen:
            continue

        seen.add(item)
        result.append(item)

    return result


def infer_action(label: str) -> str:
    text = normalize(label)

    # ---------------------------------------------------------
    # 구체적인 행동을 먼저 검사한다.
    #
    # 일반 규칙보다 우선해야 하는 표현:
    #
    # "쓸어 모은다"
    #   collect의 "모은다"보다 sweep이 우선
    #
    # "청소기로 청소한다"
    #   clean의 "청소한다"보다 vacuum이 우선
    # ---------------------------------------------------------

    priority_rules = (
        (
            "vacuum",
            (
                "청소기로 청소한다",
                "진공청소기로 청소한다",
                "청소기로",
                "진공청소기로",
            ),
        ),
        (
            "sweep",
            (
                "쓸어 모은다",
                "쓸어",
                "빗자루로 쓴다",
            ),
        ),
    )

    for action, patterns in priority_rules:
        for pattern in patterns:
            if pattern in text:
                return action

    # ---------------------------------------------------------
    # 일반 action taxonomy
    # ---------------------------------------------------------

    for action, patterns in ACTION_RULES:
        for pattern in patterns:
            if pattern in text:
                return action

    return "other"


def infer_objects(label: str) -> list[str]:
    text = normalize(label)
    objects: list[str] = []

    # ---------------------------------------------------------
    # 1. 상온 / 냉장 / 냉동 상품 처리
    # ---------------------------------------------------------

    has_product = (
        "상품" in text
        or "제품" in text
    )

    if has_product:
        if "상온" in text:
            objects.append("상온 상품")

        if "냉장" in text:
            objects.append("냉장 상품")

        if "냉동" in text:
            objects.append("냉동 상품")

    # ---------------------------------------------------------
    # 2. OBJECT_RULES 기반 객체 검색
    #
    # 긴 표현부터 검사한다.
    # ---------------------------------------------------------

    rules = sorted(
        OBJECT_RULES.items(),
        key=lambda item: max(
            len(x)
            for x in item[1]
        ),
        reverse=True,
    )

    for canonical, variants in rules:
        if any(
            variant in text
            for variant in variants
        ):
            objects.append(canonical)

    # ---------------------------------------------------------
    # 3. 복합 표현 특수 처리
    # ---------------------------------------------------------

    # "배송 봉투 또는 상자"
    if (
        "배송" in text
        and "상자" in text
    ):
        objects.append("배송 상자")

    # "쓰레기를 종류별 통에 넣는다"
    if (
        "종류별 통" in text
        or "분리수거통" in text
        or "분리수거함" in text
    ):
        objects.append("분리수거통")

    # "변기를 솔로 닦는다"
    if (
        "변기" in text
        and "솔로" in text
    ):
        objects.append("변기솔")

    # "세탁 시작 버튼"
    if "세탁 시작 버튼" in text:
        objects.append("세탁 시작 버튼")

    # ---------------------------------------------------------
    # 4. 구체 상품이 있으면 일반 상품 제거
    # ---------------------------------------------------------

    specific_product_objects = {
        "새 상품",
        "오래된 상품",
        "냉장 상품",
        "냉동 상품",
        "상온 상품",
    }

    if any(
        obj in specific_product_objects
        for obj in objects
    ):
        objects = [
            obj
            for obj in objects
            if obj != "상품"
        ]

    # ---------------------------------------------------------
    # 5. 구체 진열대가 있으면 일반 선반 제거
    # ---------------------------------------------------------

    if (
        "냉장 진열대" in objects
        or "냉동 진열대" in objects
    ):
        objects = [
            obj
            for obj in objects
            if obj != "선반"
        ]

    # ---------------------------------------------------------
    # 6. 쇼핑카트
    # ---------------------------------------------------------

    if "쇼핑카트" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "카트"
        ]

    # ---------------------------------------------------------
    # 7. 배송 봉투
    # ---------------------------------------------------------

    if "배송 봉투" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "봉투"
        ]

    # ---------------------------------------------------------
    # 8. 배송 상자
    # ---------------------------------------------------------

    if "배송 상자" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "박스"
        ]

    # ---------------------------------------------------------
    # 9. 포장 봉투
    # ---------------------------------------------------------

    if "포장 봉투" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "봉투"
        ]

    # ---------------------------------------------------------
    # 10. 불량품 / 완성품 상자
    # ---------------------------------------------------------

    if "불량품 상자" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "박스"
        ]

    if "완성품 상자" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "박스"
        ]

    # ---------------------------------------------------------
    # 11. 쓰레기봉투
    #
    # "쓰레기봉투" 자체를 의미하는 경우
    # 일반 봉투와 쓰레기를 제거한다.
    # ---------------------------------------------------------

    if "쓰레기봉투" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "봉투"
        ]

    # 쓰레기가 별도 객체로 실제 등장하는지 검사
    standalone_trash = re.search(
        r"(?<![가-힣])쓰레기"
        r"(?:를|가|는|은|도|만|와|과)?"
        r"(?=\s|$)",
        text,
    )

    if (
        "쓰레기" in objects
        and not standalone_trash
    ):
        objects = [
            obj
            for obj in objects
            if obj != "쓰레기"
        ]

    # ---------------------------------------------------------
    # 12. 차량 창문
    # ---------------------------------------------------------

    if "차량 창문" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "차량"
        ]

    # ---------------------------------------------------------
    # 13. 차량 바닥
    #
    # ['차량 바닥', '바닥', '차량']
    # ↓
    # ['차량 바닥']
    # ---------------------------------------------------------

    if "차량 바닥" in objects:
        objects = [
            obj
            for obj in objects
            if obj not in {
                "바닥",
                "차량",
            }
        ]

    # ---------------------------------------------------------
    # 14. 세탁 시작 버튼
    # ---------------------------------------------------------

    if "세탁 시작 버튼" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "버튼"
        ]
    # ---------------------------------------------------------
    # 15. "물" 오탐 제거
    # ---------------------------------------------------------

    standalone_water = re.search(
        r"(?<![가-힣])물"
        r"(?:을|를|이|가|은|는|도|만|로|에|에서|과|와)?"
        r"(?=\s|$)",
        text,
    )

    if (
        "물" in objects
        and not standalone_water
    ):
        objects = [
            obj
            for obj in objects
            if obj != "물"
        ]

    # ---------------------------------------------------------
    # 16. CAFE 구체 객체 중복 제거
    # ---------------------------------------------------------

    if "얼음컵" in objects:
        objects = [
            obj
            for obj in objects
            if obj not in {
                "컵",
                "얼음",
            }
        ]

    if "컵뚜껑" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "컵"
        ]

    if "시럽병" in objects:
        objects = [
            obj
            for obj in objects
            if obj != "시럽"
        ]

    if "음식물통" in objects:
        objects = [
            obj
            for obj in objects
            if obj not in {
                "음식물",
                "쓰레기통",
                "쓰레기",
            }
        ]

    return unique(objects)


def extract_label_words(label: str) -> list[str]:
    """
    완전한 형태소 분석기는 사용하지 않는다.
    기존 label이 짧고 구조화되어 있기 때문에
    공백 기반으로 기본 검색어만 추출한다.
    """

    text = re.sub(
        r"[^0-9A-Za-z가-힣\s]",
        " ",
        label,
    )

    raw_words = text.split()

    result = []

    for word in raw_words:
        word = word.strip()

        if len(word) < 2:
            continue

        result.append(word)

    return unique(result)


def build_keywords(
    label: str,
    action: str,
    objects: list[str],
) -> list[str]:

    keywords: list[str] = []

    # 대표 객체
    for obj in objects:
        keywords.append(obj)

        for synonym in KEYWORD_SYNONYMS.get(
            obj,
            (),
        ):
            keywords.append(synonym)

    # label 단어
    label_words = extract_label_words(label)

    keywords.extend(label_words)

    # label 안의 단어에 대한 동의어
    for word in label_words:
        for key, synonyms in KEYWORD_SYNONYMS.items():
            if (
                key in word
                or word in key
            ):
                keywords.extend(synonyms)

    # 행동 관련 검색어
    keywords.extend(
        ACTION_KEYWORDS.get(
            action,
            (),
        )
    )

    return unique(keywords)


def build_aliases(
    label: str,
    max_aliases: int = 3,
) -> list[str]:

    original = normalize(label)
    aliases: list[str] = []

    # 하나의 표현만 교체한 alias
    for source, target in ALIAS_REPLACEMENTS:
        if source not in original:
            continue

        # 이미 더 구체적인 target 표현이 존재하면
        # 중복 치환하지 않는다.
        #
        # 예:
        # "운반 카트"에
        # 카트 -> 운반 카트
        # 를 다시 적용하지 않음.
        if target in original:
            continue

        candidate = original.replace(
            source,
            target,
        )

        if candidate != original:
            aliases.append(candidate)

    # 여러 대표 치환을 동시에 적용한 버전
    combined = original

    for source, target in ALIAS_REPLACEMENTS:
        if source not in combined:
            continue

        if target in combined:
            continue

        combined = combined.replace(
            source,
            target,
        )

    if combined != original:
        aliases.append(combined)

    aliases = unique(aliases)

    return aliases[:max_aliases]


def enrich_asset(asset: dict) -> dict:
    result = dict(asset)

    label = normalize(
        result.get("label", "")
    )

    job = normalize(
        result.get("job", "")
    ).lower()

    group_id = normalize(
        result.get("group_id")
        or result.get("id", "")
    )

    # ---------------------------------------------------------
    # 기본적으로 label 기반 자동 추론
    # ---------------------------------------------------------

    action = infer_action(label)
    objects = infer_objects(label)

    # ---------------------------------------------------------
    # ASSEMBLY는 group 단위 의미를 우선 사용
    #
    # 한 작업 단계가 여러 variant 이미지로 구성되어 있으므로
    # 개별 이미지 label보다 group_id가 더 정확하다.
    # ---------------------------------------------------------

    if job == "assembly":
        # ASSEMBLY_039~175 신규 이미지에서 사용하는 부품/공구/전선 계열
        # 명사는 조립 전용 사전으로 보강한다. 기존 023~038 variant는 아래
        # group metadata가 최종 의미를 덮어쓴다.
        objects = unique(objects + infer_assembly_objects(label))

        group_metadata = ASSEMBLY_GROUP_METADATA.get(
            group_id
        )

        if group_metadata:
            action = group_metadata.get(
                "action",
                action,
            )

            objects = list(
                group_metadata.get(
                    "objects",
                    objects,
                )
            )

    # ---------------------------------------------------------
    # keyword 생성
    # ---------------------------------------------------------

    keywords = build_keywords(
        label,
        action,
        objects,
    )

    aliases = build_aliases(label)

    result["action"] = action
    result["objects"] = unique(objects)
    result["keywords"] = keywords
    result["aliases"] = aliases

    # ---------------------------------------------------------
    # search text 재구성
    # ---------------------------------------------------------

    result["search_text"] = " ".join(
        unique(
            [
                str(result.get("job", "")),
                label,
                action,
                *objects,
                *keywords,
                *aliases,
            ]
        )
    )

    return result


def main() -> None:
    parser = argparse.ArgumentParser(
        description="AAC asset metadata 초안 생성"
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT,
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
    )

    parser.add_argument(
        "--job",
        default="retail",
        help=(
            "보강할 job. "
            "기본값 retail. "
            "'all'이면 전체 처리."
        ),
    )

    args = parser.parse_args()

    data = load_json(args.input)
    assets = get_assets(data)

    target_job = args.job.strip().lower()

    enriched_count = 0

    # action asset 기준 통계
    action_asset_count = 0
    other_action_count = 0
    empty_object_count = 0

    samples: list[dict] = []

    for index, asset in enumerate(assets):
        job = str(
            asset.get("job", "")
        ).strip().lower()

        if (
            target_job != "all"
            and job != target_job
        ):
            continue

        enriched = enrich_asset(asset)

        assets[index] = enriched
        enriched_count += 1

        # -------------------------------------------------
        # 도구(tool)는 행동 분류 품질 통계에서 제외한다.
        #
        # CLEANING_TOOL_001 "대걸레" 같은 항목은
        # action=other가 정상이다.
        # -------------------------------------------------
        asset_type = str(
            enriched.get("asset_type", "")
        ).strip().lower()

        if asset_type == "action":
            action_asset_count += 1

            if enriched.get("action") == "other":
                other_action_count += 1

            if not enriched.get("objects"):
                empty_object_count += 1

            # 샘플도 실제 행동 이미지 위주로 표시
            if len(samples) < 10:
                samples.append(enriched)

    args.output.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    save_json(
        args.output,
        data,
    )

    print()
    print("=" * 70)
    print("AAC metadata enrichment")
    print("=" * 70)

    print(
        f"입력 파일       : {args.input}"
    )

    print(
        f"출력 파일       : {args.output}"
    )

    print(
        f"대상 job        : {target_job}"
    )

    print(
        f"보강 asset 수   : {enriched_count}"
    )

    print(
        f"action asset 수 : {action_asset_count}"
    )

    print(
        f"action=other    : {other_action_count}"
    )

    print(
        f"objects 없음    : {empty_object_count}"
    )

    print()
    print("샘플(action asset)")
    print("-" * 70)

    for asset in samples:
        print()

        print(
            f"[{asset.get('id')}] "
            f"{asset.get('label')}"
        )

        print(
            f"  action   : "
            f"{asset.get('action')}"
        )

        print(
            f"  objects  : "
            f"{asset.get('objects')}"
        )

        print(
            f"  keywords : "
            f"{asset.get('keywords')}"
        )

        print(
            f"  aliases  : "
            f"{asset.get('aliases')}"
        )

    print()
    print("=" * 70)


if __name__ == "__main__":
    main()