@pytest.mark.parametrize("lemma,go,a,adn,polite", TABLE)
def test_conjugation_table(lemma, go, a, adn, polite):
    f = conjugate(lemma)
    assert f is not None, lemma
    assert f.go == go
    assert f.a[0] == a
    assert f.adnominal == adn
    assert f.polite == polite
    assert f.seo()[0] == a + "서"


def test_contracted_and_full_a_forms_are_both_listed():
    assert conjugate("보다").a == ("봐", "보아")
    assert conjugate("놓다").a == ("놔", "놓아")
    assert conjugate("꺼내다").a == ("꺼내", "꺼내어")
    assert conjugate("비다").a == ("비어",)   # 한 음절 '비-'는 줄이지 않는다(*벼)


@pytest.mark.parametrize("lemma", [
    "걷다",      # 걸어(걷다, 걷기) / 걷어(걷다, 거두기) — 뜻에 따라 갈린다
    "묻다",      # 물어(묻다, 질문) / 묻어(묻다, 땅에)
    "이르다",    # 일러 / 이르러
    "푸다",      # 퍼
    "굳다",      # ㄷ 받침인데 표에 없다
    "덥다",      # ㅂ 받침인데 표에 없다(형용사)
    "낫다",      # ㅅ 받침인데 표에 없다
    "그렇다",    # ㅎ 받침 형용사
    "푸르다",    # 르 끝인데 불규칙 표에 없다
    "쓴다",      # 원형이 아니라 평서형
    "노크한다",  # 원형이 아니라 평서형
    "치우 다",   # 한 어절이 아니다
    "",
])
def test_uncertain_conjugation_returns_none(lemma):
    assert conjugate(lemma) is None


@pytest.mark.parametrize("lemma,clash", [
    ("갈다", "가세요"), ("쓸다", "쓰세요"), ("끌다", "끄세요"), ("깔다", "까세요"),
    ("들다", "드세요"), ("풀다", "푸세요"), ("팔다", "파세요"),
])
def test_rieul_polite_form_that_reads_as_another_verb_is_withheld(lemma, clash):
    """ㄹ 탈락 지시형이 다른 흔한 동사의 지시형과 같으면 만들지 않는다(다른 활용형은 낸다)."""
    f = conjugate(lemma)
    assert f is not None and f.polite is None
    assert f.go == lemma[:-1] + "고"


